package com.yuriy.openradio.mobile.view.main

import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.foundation.layout.height
import androidx.compose.material3.LinearProgressIndicator
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import com.github.jcszymansk.console.design.Console

/** The thin accent line of a list or a stream being loaded. */
@Composable
internal fun ProgressLine(modifier: Modifier = Modifier) {
    LinearProgressIndicator(
        modifier = modifier
            .fillMaxWidth()
            .height(2.dp),
        color = Console.colors.accent,
        trackColor = Console.colors.divider,
    )
}
